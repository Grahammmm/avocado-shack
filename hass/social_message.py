_VS16, _ZWJ, _KEYCAP, _BLACK_FLAG, _CANCEL_TAG = 0xFE0F, 0x200D, 0x20E3, 0x1F3F4, 0xE007F
# Unicode 16.0 emoji-sequences.txt RGI_Emoji_Tag_Sequence: England, Scotland, Wales. Other tag runs fall through.
_FLAG_TAGS = frozenset({"gbeng", "gbsct", "gbwls"})
_BASE_STARTS = [lo for lo, _ in EMOJI_BASE_RANGES]
_MOD_STARTS = [lo for lo, _ in EMOJI_MODIFIER_BASE_RANGES]


def _in(ranges, starts, cp: int) -> bool:
    i = bisect_right(starts, cp) - 1
    return i >= 0 and cp <= ranges[i][1]


def _element(cps: list, i: int):
    """(end, base) of one emoji element starting at i, or None. base is None for non-single-base elements."""
    n, cp = len(cps), cps[i]
    if cp in range(0x30, 0x3A) or cp in (0x23, 0x2A):  # keycap
        j = i + 1 + (1 if i + 1 < n and cps[i + 1] == _VS16 else 0)
        return (j + 1, None) if j < n and cps[j] == _KEYCAP else None
    if 0x1F1E6 <= cp <= 0x1F1FF:  # regional indicators only in pairs
        return (i + 2, None) if i + 1 < n and 0x1F1E6 <= cps[i + 1] <= 0x1F1FF else None
    if cp == _BLACK_FLAG and i + 1 < n and 0xE0020 <= cps[i + 1] <= 0xE007E:  # subdivision flag
        j = i + 1
        while j < n and 0xE0020 <= cps[j] <= 0xE007E: j += 1
        payload = "".join(chr(c - 0xE0000) for c in cps[i + 1:j])
        return (j + 1, None) if j < n and cps[j] == _CANCEL_TAG and payload in _FLAG_TAGS else None
    if cp in range(0x1F3FB, 0x1F400) or not _in(EMOJI_BASE_RANGES, _BASE_STARTS, cp):  # skin modifiers are not bases
        return None
    j = i + 1
    if j < n and cps[j] == _VS16: j += 1
    if j < n and 0x1F3FB <= cps[j] <= 0x1F3FF and _in(EMOJI_MODIFIER_BASE_RANGES, _MOD_STARTS, cp): j += 1
    return j, cp


def _units(text: str):
    """List of (base or None, is_sequence) per emoji unit, or None if any character is not part of a whole unit."""
    cps, units, i = [ord(c) for c in text], [], 0
    while i < len(cps):
        if text[i].isspace():
            i += 1
            continue
        first = _element(cps, i)
        if first is None: return None
        end, base, linked = first[0], first[1], False
        while end < len(cps) and cps[end] == _ZWJ:
            nxt = _element(cps, end + 1) if end + 1 < len(cps) else None
            if nxt is None: return None
            end, linked = nxt[0], True
        units.append(None if linked else base)
        i = end
    return units


def classify_social(text) -> "str | None":
    if not isinstance(text, str): return None
    # U+001C-U+001F are str.isspace()/\s but not Unicode White_Space; never normalize them away.
    if any(c in text for c in "\x1c\x1d\x1e\x1f"): return None
    phrase = re.sub(r"\s+", " ", text.strip()).casefold().rstrip(".!?")
    if phrase in PHRASES: return "social"
    if not text.strip(): return None
    units = _units(text)
    if not units: return None
    return "near" if all(base in NEAR_BASES for base in units) else "social"
